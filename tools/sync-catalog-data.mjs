#!/usr/bin/env node
/**
 * Mirror src/catalog.json into src/catalog-data.mjs.
 *
 * The bundler (tsdown) must be able to inline the catalog into a single .mjs
 * with no runtime file reads, so the runtime imports a generated ESM data
 * module while the JSON file stays the human-readable/checked artifact.
 *
 * Usage: node tools/sync-catalog-data.mjs
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const catalogPath = fileURLToPath(new URL('../src/catalog.json', import.meta.url))
const dataPath = fileURLToPath(new URL('../src/catalog-data.mjs', import.meta.url))

const catalog = JSON.parse(readFileSync(catalogPath, 'utf8'))
if (!Array.isArray(catalog.commands) || catalog.commands.length === 0) {
  throw new Error(`${catalogPath} does not contain a non-empty commands array`)
}

const content = [
  '// Generated by tools/sync-catalog-data.mjs or tools/generate-catalog.mjs. Do not edit.',
  '// Mirrors src/catalog.json so the bundled plugin has no runtime file reads.',
  `const catalog = ${JSON.stringify(catalog)}`,
  '',
  'export default catalog',
  '',
].join('\n')

writeFileSync(dataPath, content)
console.log(`[sync-catalog-data] wrote ${dataPath} (${content.length} bytes, ${catalog.commands.length} commands)`)
